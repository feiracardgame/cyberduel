const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const listeners = {}, message = {}, retry = {};
const panel = { querySelector: tag => tag === 'p' ? message : retry };
const window = { addEventListener(name, fn) { listeners[name] = fn; }, location: { reload() { window.reloaded = true; } } };
const document = { getElementById: () => panel, addEventListener(name, fn) { listeners[name] = fn; } };
vm.runInNewContext(fs.readFileSync('js/boot-status.js', 'utf8'), { window, document });
window.cyberduelBoot.loading();
assert.equal(panel.hidden, true);
listeners.error();
assert.equal(panel.hidden, false);
assert.equal(retry.hidden, false);
retry.onclick();
assert.equal(window.reloaded, true);
window.cyberduelBoot.ready();
listeners.error();
assert.equal(panel.hidden, true, 'Erros posteriores não interrompem uma partida por causa do carregamento.');
listeners.webglcontextlost();
assert.equal(panel.hidden, false);
assert.match(message.textContent, /Restaurando/);
listeners.webglcontextrestored();
assert.equal(panel.hidden, true);
console.log('Abertura: falha visível, nova tentativa e restauração da GPU validadas.');
